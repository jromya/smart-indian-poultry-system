package com.poultry.smartfarm.init;

import com.poultry.smartfarm.batch.document.Batch;
import com.poultry.smartfarm.batch.dto.BatchResponse;
import com.poultry.smartfarm.batch.repository.BatchRepository;
import com.poultry.smartfarm.report.document.BatchReport;
import com.poultry.smartfarm.report.repository.BatchReportRepository;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.stereotype.Component;

import java.time.LocalDate;
import java.time.LocalDateTime;

@Component
@Order(6)
public class Phase6DataInitializer implements CommandLineRunner {

    private static final Logger log = LoggerFactory.getLogger(Phase6DataInitializer.class);

    private final BatchReportRepository reportRepository;
    private final BatchRepository batchRepository;

    @Value("${app.seed-demo-users:true}")
    private boolean seedDemoData;

    public Phase6DataInitializer(BatchReportRepository reportRepository,
                                 BatchRepository batchRepository) {
        this.reportRepository = reportRepository;
        this.batchRepository = batchRepository;
    }

    @Override
    public void run(String... args) {
        if (!seedDemoData || reportRepository.count() > 0) {
            return;
        }
        batchRepository.findAll().stream().findFirst().ifPresent(b -> {
            BatchResponse bv = BatchResponse.fromDocument(b);
            BatchReport rpt = new BatchReport();
            rpt.setReportNumber("RPT-" + b.getBatchCode() + "-INIT");
            rpt.setFarmId(b.getFarmId());
            rpt.setFarmName(b.getFarmName());
            rpt.setBatchId(b.getId());
            rpt.setBatchCode(b.getBatchCode());
            rpt.setBatchName(b.getBatchName());
            rpt.setPoultryHouseName(b.getPoultryHouseName());
            rpt.setBreedName(b.getBreedName());
            rpt.setBatchCategory(b.getBatchCategory());
            rpt.setBatchStatus(b.getStatus());
            rpt.setChickArrivalDate(b.getChickArrivalDate());
            rpt.setReportEndDate(LocalDate.now());
            rpt.setTotalCycleDays(bv.getCurrentAgeDays());
            rpt.setStartingBirds(b.getStartingBirdQuantity());
            rpt.setTotalAdditions(b.getTotalAdditions());
            rpt.setTotalMortality(b.getTotalMortality());
            rpt.setTotalCulls(b.getTotalCulls());
            rpt.setMortalityPercentage(bv.getMortalityPercentage());
            rpt.setTotalBirdsSold(b.getTotalBirdsSold());
            rpt.setRemainingLiveBirds(bv.getCurrentLiveBirds());
            rpt.setFinalAverageWeightGrams(b.getLatestAverageWeightGrams());
            rpt.setTotalFeedConsumedKg(1480.0);
            rpt.setTotalSoldLiveWeightKg(b.getTotalSoldLiveWeightKg());
            rpt.setCalculatedFcr(1.64);
            rpt.setBreedTargetFcr(1.65);
            rpt.setTotalGoodEggsProduced(b.getTotalGoodEggsProduced());
            rpt.setTotalEggsSold(b.getTotalEggsSold());

            double chickCost = Math.round(b.getStartingBirdQuantity() * b.getPurchasePricePerChick() * 100.0) / 100.0;
            double feedCost = 62160.0;
            double medCost = 4250.0;
            double otherCost = 6800.0;
            double totalExp = chickCost + feedCost + medCost + otherCost;
            double chickenRev = Math.max(b.getTotalBirdSalesRevenue(), totalExp + 24500.0);
            double eggRev = b.getTotalEggSalesRevenue();
            double totalRev = chickenRev + eggRev + 1800.0;
            double netPl = Math.round((totalRev - totalExp) * 100.0) / 100.0;
            int denom = Math.max(1, b.getStartingBirdQuantity());

            rpt.setChickenSalesInr(chickenRev);
            rpt.setEggSalesInr(eggRev);
            rpt.setManureAndByProductSalesInr(1800.0);
            rpt.setTotalRevenueInr(totalRev);
            rpt.setChickPurchaseCostInr(chickCost);
            rpt.setFeedConsumedCostInr(feedCost);
            rpt.setMedicineAndVaccineCostInr(medCost);
            rpt.setLabourElectricityOtherCostInr(otherCost);
            rpt.setTotalExpensesInr(totalExp);
            rpt.setNetProfitLossInr(netPl);
            rpt.setCostPerBirdInr(Math.round((totalExp / denom) * 100.0) / 100.0);
            rpt.setProfitPerBirdInr(Math.round((netPl / denom) * 100.0) / 100.0);
            rpt.setProfitable(netPl >= 0);
            rpt.setPreferredLanguage("en");
            rpt.setAutoGeneratedOnCompletion(false);
            rpt.setGeneratedBy("superadmin");
            rpt.setGeneratedAt(LocalDateTime.now());
            reportRepository.save(rpt);
            log.info("Phase 6: Seeded initial Batch PDF Report '{}' in batch_reports collection.", rpt.getReportNumber());
        });
    }
}
