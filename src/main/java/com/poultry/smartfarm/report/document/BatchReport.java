package com.poultry.smartfarm.report.document;

import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;

import java.time.LocalDate;
import java.time.LocalDateTime;

@Document(collection = "batch_reports")
public class BatchReport {

    @Id
    private String id;

    @Indexed(unique = true)
    private String reportNumber;

    @Indexed
    private String farmId;
    private String farmName;

    @Indexed
    private String batchId;
    private String batchCode;
    private String batchName;

    private String poultryHouseName;
    private String breedName;
    private String batchCategory;
    private String batchStatus;

    private LocalDate chickArrivalDate;
    private LocalDate reportEndDate;
    private Integer totalCycleDays = 0;

    // Flock Balance Snapshot
    private Integer startingBirds = 0;
    private Integer totalAdditions = 0;
    private Integer totalMortality = 0;
    private Integer totalCulls = 0;
    private Double mortalityPercentage = 0.0;
    private Integer totalBirdsSold = 0;
    private Integer remainingLiveBirds = 0;

    // Growth, Feed & Egg Performance Snapshot
    private Double finalAverageWeightGrams = 0.0;
    private Double totalFeedConsumedKg = 0.0;
    private Double totalSoldLiveWeightKg = 0.0;
    private Double calculatedFcr = 0.0;
    private Double breedTargetFcr = 0.0;
    private Integer totalGoodEggsProduced = 0;
    private Integer totalEggsSold = 0;
    private Double averageHenDayPct = 0.0;

    // Non-Double-Counted Financial P&L Snapshot (INR)
    private Double chickenSalesInr = 0.0;
    private Double eggSalesInr = 0.0;
    private Double manureAndByProductSalesInr = 0.0;
    private Double totalRevenueInr = 0.0;

    private Double chickPurchaseCostInr = 0.0;
    private Double feedConsumedCostInr = 0.0;
    private Double medicineAndVaccineCostInr = 0.0;
    private Double labourElectricityOtherCostInr = 0.0;
    private Double totalExpensesInr = 0.0;

    private Double netProfitLossInr = 0.0;
    private Double costPerBirdInr = 0.0;
    private Double profitPerBirdInr = 0.0;
    private boolean profitable = true;

    private String preferredLanguage = "en";
    private boolean autoGeneratedOnCompletion = false;
    private String generatedBy;

    @CreatedDate
    private LocalDateTime generatedAt;

    public BatchReport() {
    }

    public String getId() { return id; }
    public void setId(String id) { this.id = id; }
    public String getReportNumber() { return reportNumber; }
    public void setReportNumber(String reportNumber) { this.reportNumber = reportNumber; }
    public String getFarmId() { return farmId; }
    public void setFarmId(String farmId) { this.farmId = farmId; }
    public String getFarmName() { return farmName; }
    public void setFarmName(String farmName) { this.farmName = farmName; }
    public String getBatchId() { return batchId; }
    public void setBatchId(String batchId) { this.batchId = batchId; }
    public String getBatchCode() { return batchCode; }
    public void setBatchCode(String batchCode) { this.batchCode = batchCode; }
    public String getBatchName() { return batchName; }
    public void setBatchName(String batchName) { this.batchName = batchName; }
    public String getPoultryHouseName() { return poultryHouseName; }
    public void setPoultryHouseName(String poultryHouseName) { this.poultryHouseName = poultryHouseName; }
    public String getBreedName() { return breedName; }
    public void setBreedName(String breedName) { this.breedName = breedName; }
    public String getBatchCategory() { return batchCategory; }
    public void setBatchCategory(String batchCategory) { this.batchCategory = batchCategory; }
    public String getBatchStatus() { return batchStatus; }
    public void setBatchStatus(String batchStatus) { this.batchStatus = batchStatus; }
    public LocalDate getChickArrivalDate() { return chickArrivalDate; }
    public void setChickArrivalDate(LocalDate chickArrivalDate) { this.chickArrivalDate = chickArrivalDate; }
    public LocalDate getReportEndDate() { return reportEndDate; }
    public void setReportEndDate(LocalDate reportEndDate) { this.reportEndDate = reportEndDate; }
    public Integer getTotalCycleDays() { return totalCycleDays != null ? totalCycleDays : 0; }
    public void setTotalCycleDays(Integer totalCycleDays) { this.totalCycleDays = totalCycleDays; }
    public Integer getStartingBirds() { return startingBirds != null ? startingBirds : 0; }
    public void setStartingBirds(Integer startingBirds) { this.startingBirds = startingBirds; }
    public Integer getTotalAdditions() { return totalAdditions != null ? totalAdditions : 0; }
    public void setTotalAdditions(Integer totalAdditions) { this.totalAdditions = totalAdditions; }
    public Integer getTotalMortality() { return totalMortality != null ? totalMortality : 0; }
    public void setTotalMortality(Integer totalMortality) { this.totalMortality = totalMortality; }
    public Integer getTotalCulls() { return totalCulls != null ? totalCulls : 0; }
    public void setTotalCulls(Integer totalCulls) { this.totalCulls = totalCulls; }
    public Double getMortalityPercentage() { return mortalityPercentage != null ? mortalityPercentage : 0.0; }
    public void setMortalityPercentage(Double mortalityPercentage) { this.mortalityPercentage = mortalityPercentage; }
    public Integer getTotalBirdsSold() { return totalBirdsSold != null ? totalBirdsSold : 0; }
    public void setTotalBirdsSold(Integer totalBirdsSold) { this.totalBirdsSold = totalBirdsSold; }
    public Integer getRemainingLiveBirds() { return remainingLiveBirds != null ? remainingLiveBirds : 0; }
    public void setRemainingLiveBirds(Integer remainingLiveBirds) { this.remainingLiveBirds = remainingLiveBirds; }
    public Double getFinalAverageWeightGrams() { return finalAverageWeightGrams != null ? finalAverageWeightGrams : 0.0; }
    public void setFinalAverageWeightGrams(Double finalAverageWeightGrams) { this.finalAverageWeightGrams = finalAverageWeightGrams; }
    public Double getTotalFeedConsumedKg() { return totalFeedConsumedKg != null ? totalFeedConsumedKg : 0.0; }
    public void setTotalFeedConsumedKg(Double totalFeedConsumedKg) { this.totalFeedConsumedKg = totalFeedConsumedKg; }
    public Double getTotalSoldLiveWeightKg() { return totalSoldLiveWeightKg != null ? totalSoldLiveWeightKg : 0.0; }
    public void setTotalSoldLiveWeightKg(Double totalSoldLiveWeightKg) { this.totalSoldLiveWeightKg = totalSoldLiveWeightKg; }
    public Double getCalculatedFcr() { return calculatedFcr != null ? calculatedFcr : 0.0; }
    public void setCalculatedFcr(Double calculatedFcr) { this.calculatedFcr = calculatedFcr; }
    public Double getBreedTargetFcr() { return breedTargetFcr != null ? breedTargetFcr : 0.0; }
    public void setBreedTargetFcr(Double breedTargetFcr) { this.breedTargetFcr = breedTargetFcr; }
    public Integer getTotalGoodEggsProduced() { return totalGoodEggsProduced != null ? totalGoodEggsProduced : 0; }
    public void setTotalGoodEggsProduced(Integer totalGoodEggsProduced) { this.totalGoodEggsProduced = totalGoodEggsProduced; }
    public Integer getTotalEggsSold() { return totalEggsSold != null ? totalEggsSold : 0; }
    public void setTotalEggsSold(Integer totalEggsSold) { this.totalEggsSold = totalEggsSold; }
    public Double getAverageHenDayPct() { return averageHenDayPct != null ? averageHenDayPct : 0.0; }
    public void setAverageHenDayPct(Double averageHenDayPct) { this.averageHenDayPct = averageHenDayPct; }
    public Double getChickenSalesInr() { return chickenSalesInr != null ? chickenSalesInr : 0.0; }
    public void setChickenSalesInr(Double chickenSalesInr) { this.chickenSalesInr = chickenSalesInr; }
    public Double getEggSalesInr() { return eggSalesInr != null ? eggSalesInr : 0.0; }
    public void setEggSalesInr(Double eggSalesInr) { this.eggSalesInr = eggSalesInr; }
    public Double getManureAndByProductSalesInr() { return manureAndByProductSalesInr != null ? manureAndByProductSalesInr : 0.0; }
    public void setManureAndByProductSalesInr(Double manureAndByProductSalesInr) { this.manureAndByProductSalesInr = manureAndByProductSalesInr; }
    public Double getTotalRevenueInr() { return totalRevenueInr != null ? totalRevenueInr : 0.0; }
    public void setTotalRevenueInr(Double totalRevenueInr) { this.totalRevenueInr = totalRevenueInr; }
    public Double getChickPurchaseCostInr() { return chickPurchaseCostInr != null ? chickPurchaseCostInr : 0.0; }
    public void setChickPurchaseCostInr(Double chickPurchaseCostInr) { this.chickPurchaseCostInr = chickPurchaseCostInr; }
    public Double getFeedConsumedCostInr() { return feedConsumedCostInr != null ? feedConsumedCostInr : 0.0; }
    public void setFeedConsumedCostInr(Double feedConsumedCostInr) { this.feedConsumedCostInr = feedConsumedCostInr; }
    public Double getMedicineAndVaccineCostInr() { return medicineAndVaccineCostInr != null ? medicineAndVaccineCostInr : 0.0; }
    public void setMedicineAndVaccineCostInr(Double medicineAndVaccineCostInr) { this.medicineAndVaccineCostInr = medicineAndVaccineCostInr; }
    public Double getLabourElectricityOtherCostInr() { return labourElectricityOtherCostInr != null ? labourElectricityOtherCostInr : 0.0; }
    public void setLabourElectricityOtherCostInr(Double labourElectricityOtherCostInr) { this.labourElectricityOtherCostInr = labourElectricityOtherCostInr; }
    public Double getTotalExpensesInr() { return totalExpensesInr != null ? totalExpensesInr : 0.0; }
    public void setTotalExpensesInr(Double totalExpensesInr) { this.totalExpensesInr = totalExpensesInr; }
    public Double getNetProfitLossInr() { return netProfitLossInr != null ? netProfitLossInr : 0.0; }
    public void setNetProfitLossInr(Double netProfitLossInr) { this.netProfitLossInr = netProfitLossInr; }
    public Double getCostPerBirdInr() { return costPerBirdInr != null ? costPerBirdInr : 0.0; }
    public void setCostPerBirdInr(Double costPerBirdInr) { this.costPerBirdInr = costPerBirdInr; }
    public Double getProfitPerBirdInr() { return profitPerBirdInr != null ? profitPerBirdInr : 0.0; }
    public void setProfitPerBirdInr(Double profitPerBirdInr) { this.profitPerBirdInr = profitPerBirdInr; }
    public boolean isProfitable() { return profitable; }
    public void setProfitable(boolean profitable) { this.profitable = profitable; }
    public String getPreferredLanguage() { return preferredLanguage != null ? preferredLanguage : "en"; }
    public void setPreferredLanguage(String preferredLanguage) { this.preferredLanguage = preferredLanguage; }
    public boolean isAutoGeneratedOnCompletion() { return autoGeneratedOnCompletion; }
    public void setAutoGeneratedOnCompletion(boolean autoGeneratedOnCompletion) { this.autoGeneratedOnCompletion = autoGeneratedOnCompletion; }
    public String getGeneratedBy() { return generatedBy; }
    public void setGeneratedBy(String generatedBy) { this.generatedBy = generatedBy; }
    public LocalDateTime getGeneratedAt() { return generatedAt; }
    public void setGeneratedAt(LocalDateTime generatedAt) { this.generatedAt = generatedAt; }
}
