function getCurrentLang() {
    return localStorage.getItem("poultry_lang") || "en";
}

function t(key) {
    const lang = getCurrentLang();
    const dict = POULTRY_I18N.translations[lang] || POULTRY_I18N.translations.en;
    return dict[key] || POULTRY_I18N.translations.en[key] || key;
}

function applyPageTranslations() {
    const lang = getCurrentLang();
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        el.textContent = t(key);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        el.setAttribute("placeholder", t(key));
    });
    document.querySelectorAll(".lang-selector-dropdown").forEach(sel => {
        sel.value = lang;
    });
}
